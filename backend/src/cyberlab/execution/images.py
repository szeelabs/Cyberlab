"""Environment images: turn "base image + tool packs" into a reproducible Dockerfile.

Every environment runs from an image built by this recipe, even with no tool packs, so
that it always has a real ``cyberlab`` user (uid/gid 1000, home ``/workspace``). The image
tag is derived from a hash of the rendered Dockerfile, so identical recipes are built once
and reused, and any change to the recipe produces a new tag.
"""

from __future__ import annotations

import base64
import hashlib
import re
from collections.abc import Iterable
from dataclasses import dataclass
from importlib import resources

from cyberlab.registry.models import ToolPack

_PACKAGE = re.compile(r"^[a-z0-9][a-z0-9+.-]{0,63}$")
_IMAGE = re.compile(r"^[a-z0-9][a-z0-9._/:@-]{0,254}$")
IMAGE_REPOSITORY = "cyberlab-env"
RECIPE_VERSION = "1"
FAMILIES = ("debian", "arch")  # bump to rebuild every image after changing the template

USER_SETUP = (
    "RUN set -eu; \\\n"
    '    existing="$(getent passwd 1000 | cut -d: -f1 || true)"; \\\n'
    '    if [ -n "$existing" ] && [ "$existing" != cyberlab ]; then userdel "$existing"; fi; \\\n'
    '    group="$(getent group 1000 | cut -d: -f1 || true)"; \\\n'
    '    if [ -z "$group" ]; then groupadd -g 1000 cyberlab; \\\n'
    '    elif [ "$group" != cyberlab ]; then groupmod -n cyberlab "$group"; fi; \\\n'
    "    if ! getent passwd 1000 >/dev/null; then \\\n"
    "      useradd -u 1000 -g 1000 -d /workspace -M -s /bin/bash cyberlab; fi; \\\n"
    "    mkdir -p /workspace && chown 1000:1000 /workspace\n"
)


class ImageRecipeError(ValueError):
    pass


@dataclass(frozen=True)
class ImageRecipe:
    tag: str
    dockerfile: str
    packages: tuple[str, ...]
    tool_packs: tuple[str, ...]


def collect_packages(packs: Iterable[ToolPack], family: str = "debian") -> tuple[str, ...]:
    pkgs = sorted({p for pack in packs for p in pack.packages_for(family)})
    for p in pkgs:
        if not _PACKAGE.match(p):
            raise ImageRecipeError(f"invalid package name {p!r}")
    return tuple(pkgs)


# Remote desktop: a virtual screen (Xvfb), a light window manager (Openbox), a terminal, and
# x11vnc speaking VNC over stdin/stdout (through socat), started by DESKTOP_COMMAND.
DESKTOP_PACKAGES = {
    "debian": ("openbox", "socat", "x11vnc", "xfonts-base", "xterm", "xvfb"),
    "arch": ("openbox", "socat", "x11vnc", "xorg-fonts-misc", "xorg-server-xvfb", "xterm"),
}
DESKTOP_COMMAND = "/usr/local/bin/cyberlab-desktop"


def desktop_script() -> str:
    return resources.files("cyberlab.execution").joinpath("desktop.sh").read_text("utf-8")


_URL = re.compile(r"^https://[a-z0-9.-]+(/[A-Za-z0-9._~-]+)*/?$")


def render(
    base_image: str,
    packs: Iterable[ToolPack],
    family: str = "debian",
    source_rewrite: tuple[str, str] | None = None,
    desktop: bool = False,
) -> ImageRecipe:
    """Render the Dockerfile for an environment. Pure function, no Docker needed.

    ``family`` picks the package system: ``debian`` (apt) or ``arch`` (pacman).
    """
    packs = sorted(packs, key=lambda p: p.id)
    if not _IMAGE.match(base_image):
        raise ImageRecipeError(f"invalid base image {base_image!r}")
    if family not in FAMILIES:
        raise ImageRecipeError(f"unsupported package family {family!r}")
    if source_rewrite and (family != "debian" or not all(_URL.match(u) for u in source_rewrite)):
        raise ImageRecipeError("source_rewrite needs two https URLs and an apt-based image")
    packages = collect_packages(packs, family)
    if desktop:
        packages = tuple(sorted(set(packages) | set(DESKTOP_PACKAGES[family])))
    pack_refs = tuple(f"{p.id}@{p.version}" for p in packs)

    lines = [
        "# Generated by CyberLab. Do not edit; change registry/toolpacks instead.",
        f"# recipe-version: {RECIPE_VERSION}",
        f"FROM {base_image}",
        'LABEL dev.cyberlab.managed="true" \\',
        f'      dev.cyberlab.toolpacks="{",".join(pack_refs)}"',
    ]
    if family == "debian":
        lines.append("ENV DEBIAN_FRONTEND=noninteractive")
    if packages and family == "arch":
        lines += [
            # A full upgrade with the install: Arch does not support partial upgrades.
            "RUN pacman -Syu --noconfirm --needed \\",
            *[f"      {p} \\" for p in packages],
            " && pacman -Scc --noconfirm \\",
            " && rm -rf /var/cache/pacman/pkg/*",
        ]
    elif packages:
        if source_rewrite:
            old, new = source_rewrite
            lines.append(
                # A pinned address instead of a redirector that may pick an unreachable mirror.
                f"RUN sed -i 's#{old}#{new}#g' /etc/apt/sources.list "
                "/etc/apt/sources.list.d/*.list 2>/dev/null || true"
            )
        lines += [
            # Fail over and retry instead of hanging forever on a stalled mirror connection.
            'RUN printf \'Acquire::Retries "3";\\nAcquire::http::Timeout "30";\\n'
            'Acquire::https::Timeout "30";\\n\' > /etc/apt/apt.conf.d/80cyberlab-network \\',
            " && apt-get update \\",
            " && apt-get install -y --no-install-recommends \\",
            *[f"      {p} \\" for p in packages],
            " && apt-get clean \\",
            " && rm -rf /var/lib/apt/lists/*",
        ]
    if desktop:
        # base64 keeps the script's quotes and newlines intact inside one RUN line.
        encoded = base64.b64encode(desktop_script().encode()).decode()
        lines.append(
            f"RUN echo {encoded} | base64 -d > {DESKTOP_COMMAND} && chmod 755 {DESKTOP_COMMAND}"
        )
    dockerfile = "\n".join(lines) + "\n" + USER_SETUP + "USER 1000:1000\nWORKDIR /workspace\n"
    digest = hashlib.sha256(dockerfile.encode()).hexdigest()[:16]
    return ImageRecipe(
        tag=f"{IMAGE_REPOSITORY}:{digest}",
        dockerfile=dockerfile,
        packages=packages,
        tool_packs=pack_refs,
    )


def smoke_test_commands(packs: Iterable[ToolPack]) -> list[str]:
    """Commands that must exist in an image built with these packs."""
    return sorted({t.command for p in packs for t in p.tools if t.package and t.command})
